"""Worked examples from the development split.

Claims in the report are easier to believe when a reader can see one. This
pulls real triples and shows, for each, what the surface measures compute and
what the cast extraction keeps or drops.

    python scripts/examples.py > docs/EXAMPLES.md

The dataset README asks that the canary GUID accompany any reproduction of
samples with their labels, so it is printed at the end.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

from task4.evaluate import load_split
from task4.scorers.lexical import tokenize

DATA_ROOT = "data/raw/narrative-similarity-dataset"
SUBJECT_DEPS = {"nsubj", "nsubjpass", "csubj", "agent"}
PRONOUNS = {"he", "she", "it", "they", "him", "her", "them", "his", "hers",
            "its", "their", "theirs", "i", "you", "we", "us", "me", "my",
            "this", "that", "these", "those", "who", "which", "what"}


def jaccard(a: str, b: str) -> float:
    A, B = set(tokenize(a)), set(tokenize(b))
    return len(A & B) / len(A | B) if A | B else 0.0


def cast(nlp, text: str, actors_only: bool) -> list[str]:
    """Reproduces the filter in scorers/nocoref.py, keys only."""
    doc = nlp(text)
    actors = {t.lemma_.lower() for t in doc
              if t.dep_ in SUBJECT_DEPS and t.pos_ in ("NOUN", "PROPN")}
    keys = []
    for chunk in doc.noun_chunks:
        head = chunk.root
        key = head.lemma_.lower()
        if key in PRONOUNS or head.pos_ not in ("NOUN", "PROPN"):
            continue
        if actors_only and head.pos_ != "PROPN" and key not in actors:
            continue
        if key not in keys:
            keys.append(key)
    return keys


def clip(text: str, words: int = 55) -> str:
    parts = text.split()
    return " ".join(parts[:words]) + (" [...]" if len(parts) > words else "")


def main() -> None:
    import spacy
    nlp = spacy.load("en_core_web_sm")
    triples = [t for t in load_split(DATA_ROOT, "dev") if t.a_is_closer is not None]

    scored = []
    for i, t in enumerate(triples):
        right = t.text_a if t.a_is_closer else t.text_b
        wrong = t.text_b if t.a_is_closer else t.text_a
        jr, jw = jaccard(t.anchor, right), jaccard(t.anchor, wrong)
        scored.append((i, t, right, wrong, jr, jw))

    # the clearest cases where vocabulary overlap prefers the distractor
    lexical_traps = sorted(scored, key=lambda x: x[4] - x[5])[:2]
    # and one where the character filter removes the most
    def dropped(t):
        return len(cast(nlp, t.anchor, False)) - len(cast(nlp, t.anchor, True))
    filter_cases = sorted(scored, key=lambda x: -dropped(x[1]))[:1]

    print("# Worked examples from the development split\n")
    print("Generated by `scripts/examples.py`. Text is quoted from the released")
    print("development data; summaries are clipped for length.\n")

    print("## Where vocabulary overlap prefers the distractor\n")
    print("These illustrate Section 7.3. Jaccard is computed over the same")
    print("tokenizer the L0 baseline uses.\n")
    for n, (i, t, right, wrong, jr, jw) in enumerate(lexical_traps, 1):
        print(f"### Example {n} (development triple {i})\n")
        print(f"**Anchor.** {clip(t.anchor)}\n")
        print(f"**Chosen by annotators.** {clip(right)}\n")
        print(f"**Distractor.** {clip(wrong)}\n")
        print(f"| | Jaccard with the anchor |")
        print(f"|---|---|")
        print(f"| chosen candidate | {jr:.4f} |")
        print(f"| distractor | **{jw:.4f}** |")
        print(f"\nVocabulary overlap selects the distractor by "
              f"{jw - jr:.4f}.\n")

    print("## What the character filter keeps and removes\n")
    print("This illustrates Section 7.4. A noun-chunk head is kept when it is a")
    print("proper noun, or when that noun appears as the subject of a verb")
    print("somewhere in the text. The filter is behavioural, not categorial.\n")
    for i, t, right, wrong, jr, jw in filter_cases:
        full = cast(nlp, t.anchor, False)
        actors = cast(nlp, t.anchor, True)
        removed = [k for k in full if k not in actors]
        print(f"### Development triple {i}\n")
        print(f"**Anchor.** {clip(t.anchor, 70)}\n")
        print(f"**Cast, all noun heads ({len(full)}).** "
              + ", ".join(f"`{k}`" for k in full) + "\n")
        print(f"**Cast, actors only ({len(actors)}).** "
              + ", ".join(f"`{k}`" for k in actors) + "\n")
        print(f"**Removed by the filter ({len(removed)}).** "
              + ", ".join(f"`{k}`" for k in removed) + "\n")
        print("Those removed terms are settings, objects and abstractions. The")
        print("measured effect of removing them is a drop of 4.5 points, which")
        print("is the finding Section 7.4 reports.\n")

    canary = ""
    for path in Path(DATA_ROOT).rglob("*.jsonl"):
        with open(path) as fh:
            for line in fh:
                obj = json.loads(line)
                if obj.get("canary_string"):
                    canary = obj["canary_string"]
                    break
        if canary:
            break
    if canary:
        print("## Canary\n")
        print("The dataset README asks that this string accompany any")
        print("reproduction of samples with their labels.\n")
        print("```")
        print(canary)
        print("```")


if __name__ == "__main__":
    main()
